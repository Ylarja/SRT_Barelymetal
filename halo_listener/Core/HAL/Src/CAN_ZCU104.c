/* ---------------------------- init / filters ------------------------- */

static return_code_t can_apply_rx_filters(void) {
  if (setsockopt(rx_sock, SOL_CAN_RAW, CAN_RAW_FILTER,
                 rx_filters, rx_n_filters * sizeof(struct can_filter)) < 0) {
    return RC_HW_FAULT;
  }
  return RC_OK;
}

// Creates a raw socket, sets options and filters BEFORE bind (so no frame
// slips through unfiltered), then binds it to the interface.
static int can_open_socket(int ifindex, bool own_msgs,
                           const struct can_filter *flt, size_t nflt) {
  int s = socket(PF_CAN, SOCK_RAW | SOCK_CLOEXEC, CAN_RAW);
  if (s < 0) {
    return -1;
  }
  int on = 1;
  if (own_msgs &&
      setsockopt(s, SOL_CAN_RAW, CAN_RAW_RECV_OWN_MSGS, &on, sizeof(on)) < 0) {
    goto fail;
  }
  if (setsockopt(s, SOL_SOCKET, SO_TIMESTAMPNS, &on, sizeof(on)) < 0) {
    goto fail;
  }
  // nflt == 0 -> optlen 0 -> socket receives nothing
  if (setsockopt(s, SOL_CAN_RAW, CAN_RAW_FILTER, flt, nflt * sizeof(struct can_filter)) < 0) {
    goto fail;
  }
  struct sockaddr_can addr;
  memset(&addr, 0, sizeof(addr));
  addr.can_family  = AF_CAN;
  addr.can_ifindex = ifindex;
  if (bind(s, (struct sockaddr *)&addr, sizeof(addr)) < 0) {
    goto fail;
  }
  return s;
fail:
  close(s);
  return -1;
}

return_code_t HAL_CAN_Init_Hardware(uint32_t baudrate, uint32_t hw_filter_id,
                                    uint32_t hw_filter_mask, bool rx_int_enable) {

  if (baudrate != 1000000U && baudrate != 500000U &&
      baudrate != 250000U && baudrate != 125000U) {
    // LOG HAL_CAN_ERROR_INVALID_BAUDRATE;
    return RC_INVALID_ARG;
  }
  if (rx_int_enable && CAN_Rx_Callback == NULL) {
    // LOG HAL_CAN_ERROR_NO_CALLBACK_REGISTERED;
    return RC_INVALID_ARG;
  }
  if (rx_sock >= 0) {
    return RC_OK; // already initialised
  }

  const char *ifname = getenv("HALO_CAN_IFACE");
  if (ifname == NULL || ifname[0] == '\0') {
    ifname = HALO_CAN_IFACE_DEFAULT;
  }

  // Interface must exist and be UP (bitrate is configured outside)
  int probe = socket(PF_CAN, SOCK_RAW | SOCK_CLOEXEC, CAN_RAW);
  if (probe < 0) {
    return RC_HW_FAULT;
  }
  struct ifreq ifr;
  memset(&ifr, 0, sizeof(ifr));
  strncpy(ifr.ifr_name, ifname, IFNAMSIZ - 1);
  if (ioctl(probe, SIOCGIFINDEX, &ifr) < 0) {
    close(probe);
    return RC_HW_FAULT;
  }
  int ifindex = ifr.ifr_ifindex;
  if (ioctl(probe, SIOCGIFFLAGS, &ifr) < 0 || !(ifr.ifr_flags & IFF_UP)) {
    close(probe);
    return RC_HW_FAULT;
  }
  close(probe);

  // tx_lock with priority inheritance
  pthread_mutexattr_t ma;
  pthread_mutexattr_init(&ma);
  pthread_mutexattr_setprotocol(&ma, PTHREAD_PRIO_INHERIT);
  int mrc = pthread_mutex_init(&tx_lock, &ma);
  pthread_mutexattr_destroy(&ma);
  if (mrc != 0) {
    return RC_HW_FAULT;
  }

  rx_filters[0].can_id   = (hw_filter_id   & CAN_EFF_MASK) | CAN_EFF_FLAG;
  rx_filters[0].can_mask = (hw_filter_mask & CAN_EFF_MASK) | CAN_EFF_FLAG;
  rx_n_filters = 1;

  int r = can_open_socket(ifindex, false, rx_filters, rx_n_filters);
  int t = can_open_socket(ifindex, true, NULL, 0);
  if (r < 0 || t < 0) {
    if (r >= 0) { close(r); }
    if (t >= 0) { close(t); }
    return RC_HW_FAULT;
  }
  rx_sock = r;
  tx_sock = t;

  if (rx_int_enable && !atomic_exchange(&rx_thread_started, true)) {
    if (!can_start_rx_thread()) {
      atomic_store(&rx_thread_started, false);
      close(rx_sock); rx_sock = -1;
      close(tx_sock); tx_sock = -1;
      return RC_HW_FAULT;
    }
  }
  return RC_OK;
}

// Adds one more acceptance filter (OR-ed with the existing ones).
return_code_t HAL_CAN_Add_Filter(uint32_t filter_id, uint32_t filter_mask) {
  if (rx_sock < 0) {
    return RC_HW_FAULT;
  }
  if (rx_n_filters >= CAN_MAX_FILTERS) {
    return RC_NO_RESOURCE;
  }
  rx_filters[rx_n_filters].can_id   = (filter_id   & CAN_EFF_MASK) | CAN_EFF_FLAG;
  rx_filters[rx_n_filters].can_mask = (filter_mask & CAN_EFF_MASK) | CAN_EFF_FLAG;
  rx_n_filters++;

  if (can_apply_rx_filters() != RC_OK) {
    rx_n_filters--;
    return RC_HW_FAULT;
  }
  return RC_OK;
}

