/*
 * Core/HAL/Src/CAN_ZCU104.c   (v2)
 *
 * HAL_CAN_* implementation for the ZCU104 (PetaLinux, user space).
 * Data path:  SN65HVD232 transceiver -> PS CAN1 controller (MIO24/25)
 *             -> Linux xilinx_can driver -> SocketCAN -> this file.
 *
 * Two raw sockets on the same interface:
 *   rx_sock : receives frames from other nodes, kernel filters = HW filter +
 *             sync filters installed by the PAL. No own-message echo.
 *   tx_sock : ALL transmissions go through it. RECV_OWN_MSGS is on, and its
 *             kernel filter accepts nothing except the echo of the SYNC frame
 *             currently in flight. The echo (flag MSG_CONFIRM) is generated by
 *             the driver at TX completion and provides the TX timestamp.
 *   Why not a single socket: own-frame echoes are subject to the socket
 *   filters, and a CONTROLLER node has no sync acceptance filter (the PAL
 *   installs them only on responders), so its own SYNC echo would be dropped
 *   and PAL_On_Sync_TX_Complete() would never run.
 *
 * Other differences from the Arduino/MCP2515 version:
 *  - Bitrate cannot be set from a socket. Configure it before starting:
 *        ip link set can0 type can bitrate 250000
 *        ip link set can0 txqueuelen 1000
 *        ip link set can0 up
 *    HAL_CAN_Init_Hardware() only validates the value and checks IFF_UP.
 *    (It does NOT verify the interface bitrate matches: check with
 *     `ip -details link show can0`.)
 *  - "RX interrupt" = a thread blocked in poll(); callbacks run in THREAD
 *    context, not ISR context.
 *  - Timestamps are kernel software timestamps (SO_TIMESTAMPNS), converted to
 *    CLOCK_MONOTONIC us. Get_Micros() on this target MUST use CLOCK_MONOTONIC.
 *  - HAL_CAN_Add_Filter honours filter_mask (the MCP2515 version ignores it).
 *
 * Build: link with -lpthread. Interface: env HALO_CAN_IFACE (default can0).
 */

