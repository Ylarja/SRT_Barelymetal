#define CAN_MAX_FILTERS    16   // kernel allows more; HALO needs few
#define CAN_RX_THREAD_PRIO 80   // SCHED_FIFO (needs root / CAP_SYS_NICE)
#define CAN_RX_POLL_MS     100

static int                   rx_sock = -1;
static int                   tx_sock = -1;
static struct can_filter     rx_filters[CAN_MAX_FILTERS];
static unsigned              rx_n_filters = 0;

static hal_can_rx_callback_t CAN_Rx_Callback      = NULL;
static hal_can_tx_sync_cb_t  CAN_Tx_Sync_Callback = NULL;

static pthread_t             rx_thread;
static atomic_bool           rx_thread_started = false;

// Arrival time (us, monotonic, 32 bit) of the last frame returned by Receive.
static atomic_uint_least32_t rx_timestamp_us = 0;

// Protects the sync-in-flight state and the tx_sock filter/echo queue.
// Priority inheritance: the SCHED_FIFO RX thread may wait on it.
static pthread_mutex_t       tx_lock;
static bool                  sync_pending    = false;   // guarded by tx_lock
static uint32_t              sync_pending_id = 0;       // guarded by tx_lock

/* ------------------------------ time ------------------------------ */

static uint64_t mono_now_us64(void) {
  struct timespec t;
  clock_gettime(CLOCK_MONOTONIC, &t);
  return (uint64_t)t.tv_sec * 1000000ULL + (uint64_t)t.tv_nsec / 1000ULL;
}

// Kernel stamps with CLOCK_REALTIME: convert by subtracting the frame age.
static uint32_t stamp_to_mono_us(const struct timespec *ts_rt) {
  struct timespec now_rt;
  clock_gettime(CLOCK_REALTIME, &now_rt);
  int64_t age_us = ((int64_t)now_rt.tv_sec - (int64_t)ts_rt->tv_sec) * 1000000LL +
                   ((int64_t)now_rt.tv_nsec - (int64_t)ts_rt->tv_nsec) / 1000LL;
  if (age_us < 0) {
    age_us = 0;
  }
  return (uint32_t)(mono_now_us64() - (uint64_t)age_us);
}

// recvmsg on `fd`; fills frame, msg_flags and timestamp (fallback: now).
static ssize_t can_recv_stamped(int fd, struct can_frame *fr, int *flags, uint32_t *ts_us) {
  struct iovec iov = { .iov_base = fr, .iov_len = sizeof(*fr) };
  char ctrl[CMSG_SPACE(sizeof(struct timespec))];
  struct msghdr mh;
  memset(&mh, 0, sizeof(mh));
  mh.msg_iov        = &iov;
  mh.msg_iovlen     = 1;
  mh.msg_control    = ctrl;
  mh.msg_controllen = sizeof(ctrl);

  ssize_t n = recvmsg(fd, &mh, MSG_DONTWAIT);
  if (n < 0) {
    return n;
  }
  *flags = mh.msg_flags;
  *ts_us = (uint32_t)mono_now_us64();
  for (struct cmsghdr *c = CMSG_FIRSTHDR(&mh); c != NULL; c = CMSG_NXTHDR(&mh, c)) {
    if (c->cmsg_level == SOL_SOCKET && c->cmsg_type == SCM_TIMESTAMPNS) {
      struct timespec ts_rt;
      memcpy(&ts_rt, CMSG_DATA(c), sizeof(ts_rt));
      *ts_us = stamp_to_mono_us(&ts_rt);
    }
  }
  return n;
}

/* ------------------------------- TX -------------------------------- */

static return_code_t can_write_frame(const can_msg_t *msg) {
  if (tx_sock < 0) {
    return RC_HW_FAULT;
  }
  struct can_frame fr;
  memset(&fr, 0, sizeof(fr));
  fr.can_id  = (msg->id & CAN_EFF_MASK) | CAN_EFF_FLAG;
  fr.can_dlc = (msg->dlc > CAN_MAX_DLC) ? CAN_MAX_DLC : msg->dlc;
  memcpy(fr.data, msg->data, fr.can_dlc);

  // Non-blocking: full TX queue / bus down -> fault, never stall the caller.
  ssize_t n = send(tx_sock, &fr, sizeof(fr), MSG_DONTWAIT);
  return (n == (ssize_t)sizeof(fr)) ? RC_OK : RC_HW_FAULT;
}

return_code_t HAL_CAN_Send(can_msg_t *msg) {
  if (msg == NULL) {
    // LOG HAL_CAN_ERROR_NULL_POINTER;
    return RC_INVALID_ARG;
  }
  return can_write_frame(msg);
}

// Drain the tx_sock echo queue. Caller holds tx_lock.
// If !discard and the echo of the pending sync frame is found, returns true
// and its TX-complete timestamp in *ts_us.
static bool can_drain_tx_echo_locked(bool discard, uint32_t *ts_us) {
  bool fired = false;
  if (tx_sock < 0) {
    return false;
  }
  for (;;) {
    struct can_frame fr;
    int flags = 0;
    uint32_t ts = 0;
    ssize_t n = can_recv_stamped(tx_sock, &fr, &flags, &ts);
    if (n < 0) {
      if (errno == EINTR) {
        continue;
      }
      break; // EAGAIN (empty) or hard error
    }
    if (discard || n != (ssize_t)sizeof(fr) || !(flags & MSG_CONFIRM)) {
      continue;
    }
    if (sync_pending && (fr.can_id & CAN_EFF_MASK) == sync_pending_id) {
      sync_pending = false;
      *ts_us = ts;
      fired = true;
    }
  }
  return fired;
}

// Process pending TX echoes and fire the TX sync callback if needed.
static void can_service_tx_echo(void) {
  uint32_t ts = 0;
  pthread_mutex_lock(&tx_lock);
  bool fired = can_drain_tx_echo_locked(false, &ts);
  pthread_mutex_unlock(&tx_lock);
  if (fired && CAN_Tx_Sync_Callback != NULL) {
    CAN_Tx_Sync_Callback(ts); // outside the lock; callback must stay minimal
  }
}

return_code_t HAL_CAN_Send_Sync(can_msg_t *msg) {
  if (msg == NULL) {
    return RC_INVALID_ARG;
  }
  if (tx_sock < 0) {
    return RC_HW_FAULT;
  }

  uint32_t id = msg->id & CAN_EFF_MASK;
  struct can_filter f = { .can_id   = id | CAN_EFF_FLAG,
                          .can_mask = CAN_EFF_MASK | CAN_EFF_FLAG };
  uint32_t dummy;

  pthread_mutex_lock(&tx_lock);
  sync_pending = false;
  (void)can_drain_tx_echo_locked(true, &dummy);      // drop stale echoes
  if (setsockopt(tx_sock, SOL_CAN_RAW, CAN_RAW_FILTER, &f, sizeof(f)) < 0) {
    pthread_mutex_unlock(&tx_lock);
    return RC_HW_FAULT;
  }
  // Arm BEFORE sending: the echo could be queued before send() returns.
  sync_pending_id = id;
  sync_pending    = true;
  return_code_t rc = can_write_frame(msg);
  if (rc != RC_OK) {
    sync_pending = false;
  }
  pthread_mutex_unlock(&tx_lock);
  return rc;
}

/* ------------------------------- RX -------------------------------- */

return_code_t HAL_CAN_Receive(can_msg_t *msg) {
  if (msg == NULL) {
    // LOG HAL_CAN_ERROR_NULL_POINTER;
    return RC_INVALID_ARG;
  }
  if (rx_sock < 0) {
    return RC_HW_FAULT;
  }

  // Polling mode (no RX thread): nobody else would service TX echoes.
  if (!atomic_load(&rx_thread_started)) {
    can_service_tx_echo();
  }

  for (;;) {
    struct can_frame fr;
    int flags = 0;
    uint32_t ts_us = 0;
    ssize_t n = can_recv_stamped(rx_sock, &fr, &flags, &ts_us);
    if (n < 0) {
      if (errno == EINTR) {
        continue;
      }
      if (errno == EAGAIN || errno == EWOULDBLOCK) {
        return RC_OK_NO_DATA;
      }
      return RC_HW_FAULT;
    }
    if (n != (ssize_t)sizeof(fr)) {
      continue; // not a classic CAN frame
    }
    // Only extended data frames (no RTR / error frames)
    if (!(fr.can_id & CAN_EFF_FLAG) || (fr.can_id & (CAN_RTR_FLAG | CAN_ERR_FLAG))) {
      continue;
    }

    msg->id  = fr.can_id & CAN_EFF_MASK;
    msg->dlc = (fr.can_dlc > CAN_MAX_DLC) ? CAN_MAX_DLC : fr.can_dlc;
    memcpy(msg->data, fr.data, msg->dlc);
    atomic_store(&rx_timestamp_us, ts_us);
    return RC_OK;
  }
}

uint32_t HAL_CAN_Get_RX_Timestamp(void) {
  return (uint32_t)atomic_load(&rx_timestamp_us);
}

// Plays the role of the MCP2515 INT pin ISR.
static void *can_rx_thread_fn(void *arg) {
  (void)arg;
  struct pollfd p[2] = {
    { .fd = rx_sock, .events = POLLIN, .revents = 0 },
    { .fd = tx_sock, .events = POLLIN, .revents = 0 },
  };

  for (;;) {
    int r = poll(p, 2, CAN_RX_POLL_MS);
    if (r <= 0) {
      continue;
    }
    // TX echo first: gets the sync TX timestamp to the PAL as early as possible
    if (p[1].revents & POLLIN) {
      can_service_tx_echo();
    }
    if (p[0].revents & POLLIN) {
      if (CAN_Rx_Callback != NULL) {
        CAN_Rx_Callback(); // must drain with HAL_CAN_Receive() until NO_DATA
      }
    }
    if ((p[0].revents | p[1].revents) & (POLLERR | POLLHUP | POLLNVAL)) {
      usleep(10000); // interface down/error: avoid a busy loop
    }
  }
  return NULL;
}

static bool can_start_rx_thread(void) {
  pthread_attr_t attr;
  pthread_attr_init(&attr);
  struct sched_param sp = { .sched_priority = CAN_RX_THREAD_PRIO };
  pthread_attr_setinheritsched(&attr, PTHREAD_EXPLICIT_SCHED);
  pthread_attr_setschedpolicy(&attr, SCHED_FIFO);
  pthread_attr_setschedparam(&attr, &sp);

  int rc = pthread_create(&rx_thread, &attr, can_rx_thread_fn, NULL);
  pthread_attr_destroy(&attr);
  if (rc != 0) {
    rc = pthread_create(&rx_thread, NULL, can_rx_thread_fn, NULL); // fallback
  }
  return rc == 0;
}

